/**
 * Waitlist footer. Live hrefs for claimed handles. `href: null` keeps a
 * coming-soon mark if a later network is parked.
 */
export const MARKETING_SOCIAL_LINKS = [
  { label: "X", href: "https://x.com/edgewaysapp" as const },
  { label: "Instagram", href: "https://www.instagram.com/edgeways_app/" as const },
  { label: "Facebook", href: "https://www.facebook.com/edgewaysapp" as const },
  { label: "TikTok", href: "https://www.tiktok.com/@edgewaysapp" as const },
  { label: "YouTube", href: "https://www.youtube.com/@edgewaysapp" as const },
  { label: "LinkedIn", href: "https://www.linkedin.com/company/edgewaysapp" as const },
  { label: "Slack", href: "https://edgeways.slack.com" as const },
] as const;

const ICONS = {
  X: IconX,
  Instagram: IconInstagram,
  Facebook: IconFacebook,
  TikTok: IconTikTok,
  YouTube: IconYouTube,
  LinkedIn: IconLinkedIn,
  Slack: IconSlack,
} as const;

export function MarketingSocialLinks({ className }: { className?: string }) {
  return (
    <TooltipProvider delayDuration={200}>
      <ul
        className={cn("flex flex-wrap items-center gap-2", className)}
        aria-label="Social links"
      >
        {MARKETING_SOCIAL_LINKS.map(({ label, href }) => {
          const Icon = ICONS[label];
          if (href) {
            return (
              <li key={label}>
                <a
                  href={href}
                  target="_blank"
                  rel="noopener noreferrer"
                  aria-label={`Edgeways on ${label}`}
                  className={markClass}
                >
                  <Icon className="size-4" />
                </a>
              </li>
            );
          }
          return (
            <li key={label}>
              <Tooltip>
                <TooltipTrigger asChild>
                  <button
                    type="button"
                    aria-label={`${label} — coming soon`}
                    className={markClass}
                  >
                    <Icon className="size-4" />
                  </button>
                </TooltipTrigger>
                <TooltipContent side="top" sideOffset={6}>
                  Coming soon
                </TooltipContent>
              </Tooltip>
            </li>
          );
        })}
      </ul>
    </TooltipProvider>
  );
}
